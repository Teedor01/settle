import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { NAMED, PATTERNS, type Spec } from '../src/app/domain/schema';
import { EVENT_KINDS } from '../src/app/domain/types';

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const fnName = (name: string) => `ok_${name}`;
const DEVICE_ID_PATTERN = '^[A-Za-z0-9_-]{1,100}$';
const SEQ_PATTERN = '^[0-9]{10}$';
const SEQ_MAX = 9999999999;
const HLC_MAX = 200;
const EVENT_FIELDS = ['authorUid', 'createdAt', 'deviceId', 'hlc', 'id', 'kind', 'payload', 'seq'];

function expr(spec: Spec, v: string): string {
  switch (spec.k) {
    case 'str': {
      if (spec.pat === 'hex64') return `${v}.matches(${q(PATTERNS.hex64)})`;
      if (spec.pat === 'id') return `${v}.matches(${q(`^[A-Za-z0-9_.:-]{${Math.max(spec.min ?? 0, 1)},${spec.max}}$`)})`;
      return `(${v} is string${spec.min ? ` && ${v}.size() >= ${spec.min}` : ''} && ${v}.size() <= ${spec.max}${spec.pat ? ` && ${v}.matches(${q(PATTERNS[spec.pat])})` : ''})`;
    }
    case 'int': return `(${v} is int && ${v} >= ${spec.min} && ${v} <= ${spec.max})`;
    case 'bool': return `(${v} is bool)`;
    case 'enum': {
      // one anchored alternation instead of a list literal (each literal is an evaluated expression); values are plain words, checked here so nothing needs escaping
      for (const x of spec.values) if (!/^[A-Za-z0-9_-]+$/.test(x)) throw new Error(`enum value ${x} needs regex escaping`);
      return `${v}.matches(${q(`^(${spec.values.join('|')})$`)})`;
    }
    case 'null': return `(${v} == null)`;
    case 'oneOf': return `(${spec.of.map((s) => expr(s, v)).join(' || ')})`;
    case 'ref': return `${fnName(spec.name)}(${v})`;
    default: throw new Error(`${spec.k} must be a named entry, not inline`);
  }
}

function refsOf(spec: Spec): string[] {
  switch (spec.k) {
    case 'ref': return [spec.name];
    case 'oneOf': return spec.of.flatMap(refsOf);
    case 'list': return refsOf(spec.of);
    case 'map': return [...Object.values(spec.req), ...Object.values(spec.opt ?? {})].flatMap(refsOf);
    default: return [];
  }
}

function entryFunction(name: string, spec: Spec): string {
  if (spec.k === 'list') {
    // Every index up to the limit is checked, NESTED so that evaluation stops at the end of the actual list: a list of n items costs n checks, not `max`.
    // Same verdict as checking each index independently: (size <= i || (element i ok && rest)).
    const chain = (i: number): string => (i === spec.max - 1 ? `(v.size() <= ${i} || ${expr(spec.of, `v[${i}]`)})` : `(v.size() <= ${i} || (${expr(spec.of, `v[${i}]`)}\n        && ${chain(i + 1)}))`);
    return `    function ${fnName(name)}(arg) {\n      let v = arg;\n      return v is list && v.size() <= ${spec.max}\n        && ${chain(0)};\n    }`;
  }
  if (spec.k === 'map') {
    const opt = spec.opt ?? {};
    const all = [...Object.keys(spec.req), ...Object.keys(opt)].sort();
    const req = Object.keys(spec.req).sort();
    const parts = [
      // (no separate `is map`: keys() on a non-map is an evaluation error = deny.)
      // hasOnly bounds the fields to the schema; every required field is then READ below, and reading an absent field is an evaluation error = deny,
      // so a separate hasAll would add cost (Firestore's 1000-expression limit) without changing any verdict.
      Object.keys(opt).length === 0
        // no optional fields: exactly N entries, and each of the N required fields is read below (present, or deny), so the key set is exactly the schema's
        ? `v.size() == ${req.length}`
        : `v.keys().hasOnly([${all.map(q).join(', ')}])`,
      ...req.map((k) => expr(spec.req[k] as Spec, `v.${k}`)),
      ...Object.keys(opt).sort().map((k) => `(!(${q(k)} in v) || ${expr(opt[k] as Spec, `v.${k}`)})`),
    ];
    return `    function ${fnName(name)}(arg) {\n      let v = arg;\n      return ${parts.join('\n        && ')};\n    }`;
  }
  throw new Error(`NAMED.${name} must be a map or a list`);
}

export function generateRules(): string {
  // dependencies first: a function is always defined before any function that calls it (no reliance on forward references)
  const order: string[] = [];
  const visit = (name: string) => {
    if (order.includes(name)) return;
    for (const d of refsOf(NAMED[name] as Spec)) visit(d);
    order.push(name);
  };
  Object.keys(NAMED).forEach(visit);
  const helpers = order.map((n) => entryFunction(n, NAMED[n] as Spec)).join('\n\n');
  const dispatch = EVENT_KINDS.map((k) => `(kind == ${q(k)} && ${fnName(`payload_${k}`)}(p))`).join('\n        || ');
  return `rules_version = '2';
// GENERATED by scripts/generate-rules.ts from src/app/domain/schema.ts. DO NOT EDIT BY HAND: change the schema and run \`npm run rules:generate\`.
//
// What these rules enforce on every write to an event (single write, batch or transaction: rules apply per document write on every path):
//  - only the authenticated owner of /users/{uid} can create events there, and the event must name that user as its author (authorUid);
//  - the document has EXACTLY the fields ${EVENT_FIELDS.join(', ')} (no others), with the documented types and formats;
//  - the payload is a map with ONLY the fields the schema names for its kind, each with the declared type, format and maximum length,
//    list sizes bounded and every list element checked (unrolled), nested maps checked the same way. Document-content fields are not in the schema;
//  - events are IMMUTABLE: create-only, never updated or deleted by any client.
// What rules CANNOT do: sum the characters across fields, or tell a legitimate quotation from copied document text that fits inside a field's limit.
// Not verified until the emulator tests (npm run test:emulator) pass.
service cloud.firestore {
  match /databases/{database}/documents {

    function isOwner(uid) { return request.auth != null && request.auth.uid == uid; }
    function deviceIdOk(d) { return d is string && d.matches(${q(DEVICE_ID_PATTERN)}); }

${helpers}

    function payload_ok(kindArg, payloadArg) {
      let kind = kindArg;
      let p = payloadArg;
      return ${dispatch};
    }

    function eventOk(uid, deviceId, seq, doc) {
      let d = doc;
      return d.keys().hasAll([${EVENT_FIELDS.map(q).join(', ')}])
        && d.keys().hasOnly([${EVENT_FIELDS.map(q).join(', ')}])
        && deviceIdOk(deviceId)
        && seq.matches(${q(SEQ_PATTERN)})
        && d.authorUid is string && d.authorUid == request.auth.uid && uid == request.auth.uid
        && d.id == deviceId + '-' + seq
        && d.deviceId == deviceId
        && d.seq is int && d.seq >= 1 && d.seq <= ${SEQ_MAX}
        && d.hlc is string && d.hlc.size() <= ${HLC_MAX} && d.hlc.matches(${q(PATTERNS.hlc)})
        && d.kind is string && d.kind in [${EVENT_KINDS.map(q).join(', ')}]
        && d.createdAt == request.time
        && d.payload is map
        && payload_ok(d.kind, d.payload);
    }

    function deviceDocOk(deviceId, doc) {
      let d = doc;
      return d.keys().hasAll(['deviceId', 'lastSeen'])
        && d.keys().hasOnly(['deviceId', 'lastSeen'])
        && deviceIdOk(deviceId)
        && d.deviceId == deviceId
        && d.lastSeen == request.time;
    }

    match /users/{uid}/devices/{deviceId} {
      allow read: if isOwner(uid);
      allow create, update: if isOwner(uid) && deviceDocOk(deviceId, request.resource.data);
      allow delete: if false;

      match /events/{seq} {
        allow read: if isOwner(uid);
        allow create: if isOwner(uid) && eventOk(uid, deviceId, seq, request.resource.data);
        allow update, delete: if false;
      }
    }
  }
}
`;
}

function main(argv: string[]): number {
  const file = path.resolve('firestore.rules');
  const text = generateRules();
  if (argv.includes('--check')) {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text;
    console.log(same ? 'firestore.rules matches the schema.' : 'firestore.rules is OUT OF DATE: run npm run rules:generate');
    return same ? 0 : 1;
  }
  fs.writeFileSync(file, text);
  console.log(`wrote ${file} (${text.split('\n').length} lines, ${Object.keys(NAMED).length} generated functions)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) process.exit(main(process.argv.slice(2)));
